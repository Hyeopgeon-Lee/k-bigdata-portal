-- All historical Alumni Network sheet records are stored in a private-by-RLS JSONB archive.
-- Source IDs and unmodified data make verification and rollback possible.
create table if not exists public.alumni_network_records (
 source_kind text not null
   check (source_kind in ('alumni','alumni_news','jobs','contact_requests',
     'job_mail_logs','alumni_news_mail_logs','alumni_consent_logs',
     'career_consent_invites','alumni_news_consent_invites','admins','logs','pin_reset_requests')),
 source_id text not null,
 data jsonb not null,
 updated_at timestamptz not null default now(),
 primary key(source_kind,source_id),
 constraint alumni_network_record_length check (length(source_id) between 1 and 120)
);
create index if not exists alumni_network_kind_status_idx
 on public.alumni_network_records(source_kind,((data->>'status')));
create index if not exists alumni_network_alumni_ref_idx
 on public.alumni_network_records(source_kind,((data->>'alumni_id')));
alter table public.alumni_network_records enable row level security;
revoke all on public.alumni_network_records from public,anon,authenticated;
grant select,insert,update,delete on public.alumni_network_records to service_role;
comment on table public.alumni_network_records is
 'Private-by-RLS source rows migrated from Google Sheets; ONLY service-role backend accesses full PII. Client gets sanitized projections.';

create table if not exists public.alumni_network_mail_outbox (
 id bigint generated by default as identity primary key,
 event_type text not null,
 record_kind text not null,
 record_id text not null,
 recipient text not null,
 subject text not null,
 html text not null,
 status text not null default 'pending' check(status in ('pending','sending','sent','failed')),
 provider_id text,
 error_message text,
 created_at timestamptz not null default now(),
 sent_at timestamptz,
 unique(event_type,record_kind,record_id,recipient)
);
alter table public.alumni_network_mail_outbox enable row level security;
revoke all on public.alumni_network_mail_outbox from public,anon,authenticated;
grant select,insert,update,delete on public.alumni_network_mail_outbox to service_role;
comment on table public.alumni_network_mail_outbox is
 'Mail outbox for authenticated alumni network submissions. Prevent repeated notification by unique event ID.';
