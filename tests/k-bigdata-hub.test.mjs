import assert from 'node:assert/strict';
import {readFileSync,statSync} from 'node:fs';
import {services,portalNavLinks} from '../js/services.js';
import {portalPages} from '../js/portal-navigation-model.mjs';
import {groupSearchResults} from '../js/search.js';
const read=file=>readFileSync(new URL('../'+file,import.meta.url),'utf8');
const id='k-bigdata-hub',url=id+'.html',html=read(url);
assert.equal(services.find(s=>s.id===id)?.url,url);
assert.equal(portalNavLinks.find(s=>s.id===id)?.group,'learning');
assert.equal(portalPages[id].group,'learning');
assert.ok(groupSearchResults('K-BigData Hub').some(group=>group.items.some(item=>item.url===url)));
assert.ok(read('index.html').includes('class="kh-shortcut" href="'+url+'"'));
assert.ok(read('coding.html').includes('class="kh-shortcut kh-coding-link" href="'+url+'"'));
assert.match(html,/https:\/\/chromewebstore\.google\.com\/detail\/k-bigdata-hub\/ifmnjdcbbojifiogejdhfonbidmpolfp\?hl=ko/);
assert.match(html,/<video[^>]+controls[^>]+playsinline/);
assert.match(html,/<source src="media\/k-bigdata-hub-demo\.mp4" type="video\/mp4">/);
assert.ok(statSync(new URL('../media/k-bigdata-hub-demo.mp4',import.meta.url)).size>100000);
assert.ok(html.includes('‘문제도 함께 올리기’는 끄고'));
assert.ok(html.includes('공개 저장소에는 직접 작성한 코드만 올리세요'));
assert.match(html,/<meta name="robots" content="noindex, nofollow, noarchive">/);
console.log('PASS: Hub service registry, search, portal shortcuts, MP4 and Chrome install link.');
