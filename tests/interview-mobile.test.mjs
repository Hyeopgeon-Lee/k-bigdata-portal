const ui=readFileSync(new URL('../js/interview-ui.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../css/interview.css',import.meta.url),'utf8');
assert.ok(!page.includes('id="portal-query"'));
assert.ok(page.includes('content="noindex, nofollow"'));
assert.ok(page.includes('id="list-controls" hidden'));
assert.ok(!page.includes('interview-editorial'));
assert.ok(!ui.includes('interviewEditorialSources'));
assert.ok(!page.includes('browse-one')&&!page.includes('browse-ten'));
for(const state of ['HOME','BROWSE','PRACTICE_ONE','PRACTICE_TEN','COMPLETE'])assert.ok(ui.includes(state));
assert.ok(ui.includes('available.slice(0,limit)'));
assert.ok(ui.includes('limit+=20'));
for(const param of ['id','category','job','difficulty'])assert.ok(ui.includes('params.get("'+param+'")'));
assert.ok(!ui.includes('localStorage')&&!ui.includes('sessionStorage'));
assert.ok(css.includes('env(safe-area-inset-bottom)'));
assert.ok(css.includes('body[data-page="interview"]'));
console.log('PASS: combined difficulty/category/job/search, 150 preserved progressive disclosures, legacy categories, paging, states, no storage, noindex and scoped mobile CSS.');
