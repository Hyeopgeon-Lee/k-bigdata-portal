import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {readyErrorMessage,table} from '../js/ready-common.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('ready.html'),js=read('js/ready.js'),css=read('css/ready.css');
assert.equal((html.match(/<h1\b/g)||[]).length,1,'one shared page title');
assert.match(html,/<main id="main-content" class="ready-main"/);
assert.match(html,/<div class="container ready-workspace">/);
assert.match(html,/css\/ready.css\?v=20261128-ready-ui-2/);
assert.match(js,/if\(role\?\.isAdmin===true\)\{accessPanel\('admin'\);return\}/);
assert.match(js,/href="admin\/ready.html"/);
assert.match(js,/if\(role\?\.profile&&\(role\.profile\.signup_type!=='student'/);
assert.match(js,/다시 불러오기/);
assert.equal(readyErrorMessage('STUDENT_REQUIRED'),'취업 준비 점검은 재학생 계정으로 이용할 수 있습니다.');
assert.match(readyErrorMessage('DATABASE_ERROR'),/정보를 불러오지 못했습니다/);
assert.doesNotMatch(readyErrorMessage('INTERNAL_SECRET_CODE'),/INTERNAL_SECRET_CODE/);
assert.match(table(['저장소'],[['hello']]),/data-label="저장소"><div class="ready-cell">hello/);
assert.match(css,/\.ready-workspace \.ready-table tbody td::before\{content:attr\(data-label\)/);
assert.match(css,/\.ready-workspace \.ready-tabs\{grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.doesNotMatch(html,/ready-hero/);
console.log('PASS: shared portal shell, administrator/student route separation, Korean errors, mobile table labels and independent READY cache version.');
