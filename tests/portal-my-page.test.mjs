import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const html=read('mypage.html'),js=read('js/my-page.js'),css=read('css/my-page.css');
const auth=read('js/portal-auth.mjs'),model=read('js/portal-navigation-model.mjs');
const sql=read('supabase/migrations/20261112121100_my_page_student_academic_status_self_service.sql');
const graduatedSql=read('supabase/migrations/20261112224000_add_graduated_status_to_my_page_and_keep_graduate_learning_access.sql');
const phoneSql=read('supabase/migrations/20261113051000_mobile_phone_signup_profile_edit.sql');
assert.match(model,/mypage: \{title:'마이페이지'/,'page registered with portal shell');
assert.match(auth,/title:"마이페이지".*href:"mypage.html"/,'account drawer links to my page');
assert.match(html,/id="learning-lock"/,'page gated from first paint');
assert.match(html,/data-module="js\/my-page.js\?v=/,'loads only after authentication');
assert.match(html,/id="my-page-password-form"/);
assert.match(html,/name="academic_status" value="1"/);
assert.match(html,/name="academic_status" value="2"/);
assert.match(html,/name="academic_status" value="leave"/);
assert.match(html,/name="academic_status" value="graduated"/,"graduation can be selected");
assert.doesNotMatch(html,/id="my-page-graduation-phone"/,"graduation no longer requires a phone");
assert.match(html,/id="my-page-contact-panel"/,"phone has a separate editable section");
assert.match(html,/id="my-page-mobile-form"/,"phone form is independently saved");
assert.match(html,/id="my-page-mobile-phone".*type="tel"/,"mobile-friendly input");
assert.match(html,/id="my-page-mobile-summary"/,"phone stored on own profile");
assert.match(html,/학과 포털 내부 정보/);
assert.match(js,/api\.auth\.signInWithPassword\(/,'current password verified');
assert.match(js,/api\.auth\.updateUser\(\{password:next\}\)/,'Supabase Auth updates password');
assert.match(js,/api\.rpc\("start_portal_session"\)/,'new login session authorized');
assert.match(js,/api\.rpc\("update_my_academic_status",\{p_status:next\}\)/,"academic status no longer sends phone");
assert.match(js,/api\.rpc\("update_my_mobile_phone",\{p_mobile_phone:phone\}\)/,"phone saves separately");
assert.doesNotMatch(js,/phoneInput\.required=graduating/,"graduation does not require phone");
assert.match(js,/!validMobile\(phone\)/,"phone form validates before saving");
assert.match(js,/profile\.mobile_phone=mobileDigits\(phone\)/,"saved number immediately updates own profile");
assert.match(js,/profile\.signup_type==="student"/,'self-service status for students only');
assert.match(html,/id="my-page-academic-lock-note"/,'registered graduates have read-only account notice');
assert.match(js,/api\.rpc\("my_alumni_profile_registered"\)/,'check alumni registration in server-side RPC');
assert.match(js,/registeredAlumni!==false/,'fail closed when registration status is unknown');
assert.match(js,/lockNotice\.hidden=false/,'show explanation for alumni-registered members');
const alumniLockSql=read('supabase/migrations/20261114010000_lock_registered_alumni_academic_status.sql');
assert.match(alumniLockSql,/CREATE OR REPLACE FUNCTION public\.my_alumni_profile_registered\(\)/i);
assert.match(alumniLockSql,/public\.alumni_profiles a where a\.user_id=v_id/i,'registered alumni bound to authenticated user');
assert.match(alumniLockSql,/raise exception 'ACADEMIC_STATUS_CHANGE_NOT_ALLOWED'/i,'server refuses academic change');
assert.match(alumniLockSql,/revoke all on function public\.my_alumni_profile_registered\(\) from public,anon/i,'anonymous access denied');
assert.match(alumniLockSql,/grant execute on function public\.my_alumni_profile_registered\(\) to authenticated/i,'RPC only for signed-in members');
assert.match(js,/sessionStorage\.setItem\("portal:mypage-success"/,'user gets result after reload');
assert.match(css,/@media\(max-width:740px\)/,'mobile layout present');
assert.match(sql,/v_id uuid := auth\.uid\(\)/,'uses session user id only');
assert.match(sql,/private\.portal_read_allowed\(\)/,'server checks session');
assert.match(sql,/p_status not in \('1','2','leave'\)/,'status allowlist');
assert.match(sql,/v_old\.signup_type<>'student'/,'staff/alumni blocked');
assert.match(sql,/role='super_admin'/,'admin protected');
assert.match(sql,/revoke all on function public\.update_my_academic_status/,'RPC public role restricted');
assert.match(sql,/private\.portal_academic_status_history/,'status audit trail');
assert.match(graduatedSql,/p_status not in \('1','2','leave','graduated'\)/,'graduation accepted by RPC');
assert.match(graduatedSql,/p\.signup_type in \('student','alumni'\) and p\.enrollment_status='graduated'/,'graduate can log in');
