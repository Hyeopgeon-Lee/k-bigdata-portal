assert.match(js,/profile\.enrollment_status==="graduated"/,'graduate status shown in UI');
assert.match(phoneSql,/FUNCTION public\.register_portal_member_v4/i,"signup includes mobile");
assert.match(phoneSql,/FUNCTION public\.update_my_mobile_phone/i,"self-service phone RPC exists");
assert.match(phoneSql,/MOBILE_PHONE_REQUIRED/,"registration and phone editor validate required contact");
assert.match(phoneSql,/INVALID_MOBILE_PHONE/,"server validates mobile format");
const academicSql=phoneSql.split(/CREATE OR REPLACE FUNCTION public\.update_my_academic_status/i)[1];
assert.ok(academicSql,"graduation RPC redefined");
assert.doesNotMatch(academicSql,/MOBILE_PHONE_REQUIRED/,"graduation does not require a phone");
assert.match(phoneSql,/grant execute on function public\.update_my_mobile_phone\(text\) to authenticated/i,"phone RPC only for authenticated");
for(const f of ['js/my-page.js','js/portal-auth.mjs','js/portal-navigation-model.mjs']){
 execFileSync('node',['--check',new URL('../'+f,import.meta.url).pathname],{stdio:'pipe'});
}
