import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {codingProblems as sampleProblems} from '../data/coding-samples.js';
import {javaProblems} from '../data/coding-java-98.js';
import {cFoundationProblems} from '../data/coding-c-foundations.js';
import {cAdvancedProblems} from '../data/coding-c-advanced.js';
import {pythonFoundationProblems} from '../data/coding-python-foundations.js';
import {pythonAdvancedProblems} from '../data/coding-python-advanced.js';
import {ubuntuPptProblems} from '../data/coding-ubuntu-ppt.js';
import {buildBank} from '../js/practical-core.js';
const check=process.argv.includes("--check");
const emit=(path,text)=>{const url=new URL("../"+path,import.meta.url);if(check){if(readFileSync(url,"utf8")!==text)throw Error("Stale index: "+path);}else writeFileSync(url,text);};
const write=(path,data)=>emit(path,JSON.stringify(data)+"\n");
const read=path=>JSON.parse(readFileSync(new URL('../'+path,import.meta.url),'utf8'));
const coding=[...sampleProblems.filter(p=>p.language!=='linux'),...javaProblems,...cFoundationProblems,...cAdvancedProblems,...pythonFoundationProblems,...pythonAdvancedProblems,...ubuntuPptProblems];
const codingIndex=coding.map(({id,language,title,topic,level,statement})=>({id,language,title,topic,level,statement})).sort((a,b)=>a.language.localeCompare(b.language)||Number(a.id.split('-').at(-1))-Number(b.id.split('-').at(-1)));
if(codingIndex.length!==350||new Set(codingIndex.map(x=>x.id)).size!==350)throw Error('Coding bank size mismatch');
emit('data/coding-index.js','// Generated by scripts/build-learning-indexes.mjs\nexport const codingIndex='+JSON.stringify(codingIndex)+';\n');
const imported=read('data/practical/normalized.json');
const practical=buildBank([...read('data/practical/questions.json'),...read('data/practical/reconstructed-extra.json'),...imported.questions],read('data/practical/exam-history.json'));
mkdirSync(new URL('../data/practical/indexed/',import.meta.url),{recursive:true});
const indexKeys=['id','language','title','question','questionType','concepts','history','sourceType','difficulty','code'];
write('data/practical/indexed/index.json',{bank:practical.map(q=>Object.fromEntries(indexKeys.filter(k=>k in q).map(k=>[k,q[k]]))),aliases:imported.aliases});
for(const lang of ['C','Java','Python','SQL']){
 const rows=practical.filter(q=>q.language===lang).map(q=>Object.fromEntries(Object.entries(q).filter(([key])=>key==='id'||!indexKeys.includes(key))));
 write('data/practical/indexed/'+lang.toLowerCase()+'.json',rows);
}
console.log('Learning indexes generated:',codingIndex.length,practical.length);
